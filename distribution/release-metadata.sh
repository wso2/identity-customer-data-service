#!/usr/bin/env bash
#
# Publishes the release compatibility metadata beside the distribution zips.
#
# A release has to say enough for installation and enablement tooling to pick
# the right artifact and check the environment it is going into, without
# downloading and unpacking a zip first. That is what this file is: the product
# identity, the platform artifacts with their checksums, and the compatibility
# the pack itself carries in repository/conf/compatibility.yaml.
#
#   release-metadata.sh <compatibility.yaml> <dist-dir>
#
# Called by `make dist`. PRODUCT_NAME, PACK_VERSION and PLATFORMS come from the
# Makefile, so the names here cannot drift from the packs that were built.

set -euo pipefail

COMPATIBILITY="${1:?usage: release-metadata.sh <compatibility.yaml> <dist-dir>}"
DIST_DIR="${2:?usage: release-metadata.sh <compatibility.yaml> <dist-dir>}"

: "${PRODUCT_NAME:?PRODUCT_NAME is not set}"
: "${PACK_VERSION:?PACK_VERSION is not set}"
: "${PLATFORMS:?PLATFORMS is not set}"

[ -f "$COMPATIBILITY" ] || { echo "release-metadata: $COMPATIBILITY not found" >&2; exit 1; }

OUTPUT="$DIST_DIR/$PRODUCT_NAME-$PACK_VERSION-release-metadata.yaml"

# The checksum file holds "<sum>  <name>"; only the sum is wanted here.
checksum_of() {
  local file="$1.sha256"
  [ -f "$file" ] || { echo ""; return; }
  awk '{print $1; exit}' "$file"
}

{
  echo "# Release compatibility metadata for $PRODUCT_NAME $PACK_VERSION."
  echo "#"
  echo "# Generated by distribution/release-metadata.sh during \`make dist\`."
  echo "# The compatibility section is the pack's own repository/conf/compatibility.yaml,"
  echo "# so what a release claims and what an installed pack enforces are one statement."
  echo
  echo "product: $PRODUCT_NAME"
  echo "version: \"$PACK_VERSION\""
  echo
  echo "platforms:"
  for platform in $PLATFORMS; do
    os="${platform%/*}"
    arch="${platform#*/}"
    pack="$PRODUCT_NAME-$os-$arch-$PACK_VERSION"
    zip="$DIST_DIR/$pack.zip"
    [ -f "$zip" ] || { echo "release-metadata: $zip was not built" >&2; exit 1; }
    echo "  - os: $os"
    echo "    arch: $arch"
    echo "    artifact: $pack.zip"
    echo "    u2_product: $pack"
    echo "    size_bytes: $(wc -c < "$zip" | tr -d ' ')"
    echo "    sha256: $(checksum_of "$zip")"
  done
  echo
  echo "compatibility:"
  # Indented wholesale rather than re-emitted field by field, so a field added
  # to compatibility.yaml appears here without this script changing.
  sed -e 's/^/  /' -e 's/[[:space:]]*$//' "$COMPATIBILITY"
} > "$OUTPUT"

echo "  -> $OUTPUT"
